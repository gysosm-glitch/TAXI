for s in ("List Bullet", "List Number"):
    set_font(doc.styles[s], 10.5)

def p(text, bold_prefix=None, color=None, size=None, italic=False):
    para = doc.add_paragraph()
    if bold_prefix:
        r = para.add_run(bold_prefix); r.bold = True
    r = para.add_run(text)
    if color: r.font.color.rgb = color
    if size: r.font.size = Pt(size)
    r.italic = italic
    return para

def bullets(items, style="List Bullet"):
    for it in items:
        if isinstance(it, tuple):
            para = doc.add_paragraph(style=style); r = para.add_run(it[0]); r.bold = True; para.add_run(it[1])
        else:
            doc.add_paragraph(it, style=style)

def shade(cell, hex_):
    tcpr = cell._tc.get_or_add_tcPr()
    sh = OxmlElement("w:shd"); sh.set(qn("w:val"), "clear"); sh.set(qn("w:color"), "auto"); sh.set(qn("w:fill"), hex_)
    tcpr.append(sh)

def table(rows, widths=None, highlight_col=None):
    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
    t.style = "Table Grid"
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            c = t.cell(i, j); c.text = ""
            r = c.paragraphs[0].add_run(str(val)); r.font.size = Pt(9.5)
            if i == 0:
                r.bold = True; r.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF); shade(c, "0F2A22")
            elif highlight_col is not None and j == highlight_col:
                r.bold = True; shade(c, "E1F5EE")
            if widths: c.width = Cm(widths[j])
    doc.add_paragraph()
    return t

def note(text):
    p(text, color=MUTED, size=9, italic=True)

